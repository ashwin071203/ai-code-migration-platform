using System.Text.Json;
using System.Text.RegularExpressions;
using MigrationPlatform.MigrationEngine.Interfaces;
using MigrationPlatform.MigrationEngine.Models;

namespace MigrationPlatform.MigrationEngine.Providers;

public sealed partial class SpringToAspNetProvider : IMigrationProvider
{
    public bool CanHandle(string sourceTechnology, string targetTechnology) => sourceTechnology.Equals("Spring Boot", StringComparison.OrdinalIgnoreCase) && targetTechnology.Equals("ASP.NET Core Web API", StringComparison.OrdinalIgnoreCase);

    public async Task<MigrationResult> ExecuteAsync(MigrationRequest request, CancellationToken cancellationToken)
    {
        if (!Directory.Exists(request.SourceRoot)) return new("Failed", null, [], [], "The source workspace does not exist.");
        Directory.CreateDirectory(request.OutputRoot);
        var files = new List<string>();
        var warnings = new List<string> { "Spring dependency injection and security require ASP.NET Core registration review.", "JPA/Hibernate mappings require EF Core model review.", "Maven dependencies require NuGet mapping review." };
        foreach (var sourceFile in Directory.EnumerateFiles(request.SourceRoot, "*", SearchOption.AllDirectories))
        {
            cancellationToken.ThrowIfCancellationRequested();
            var relative = Path.GetRelativePath(request.SourceRoot, sourceFile);
            var fileName = Path.GetFileName(relative);
            var destinationRelative = fileName.Equals("application.properties", StringComparison.OrdinalIgnoreCase) ? "appsettings.json" : Path.ChangeExtension(relative, Path.GetExtension(relative).Equals(".java", StringComparison.OrdinalIgnoreCase) ? ".cs" : Path.GetExtension(relative));
            var destination = Path.Combine(request.OutputRoot, destinationRelative);
            Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
            var source = await File.ReadAllTextAsync(sourceFile, cancellationToken);
            var content = fileName.Equals("application.properties", StringComparison.OrdinalIgnoreCase) ? ConvertProperties(source) : sourceFile.EndsWith(".java", StringComparison.OrdinalIgnoreCase) ? ConvertJava(source, warnings) : source;
            await File.WriteAllTextAsync(destination, content, cancellationToken);
            files.Add(destinationRelative);
        }
        await File.WriteAllTextAsync(Path.Combine(request.OutputRoot, "FORGESHIFT-MANUAL-REVIEW.md"), "# Manual review required\n\nSpring Boot source was mapped into an ASP.NET Core-shaped workspace. Review controllers, dependency injection, persistence, security, configuration, tests, and NuGet dependencies before use.\n\n## Warnings\n\n" + string.Join("\n", warnings.Distinct().Select(warning => $"- {warning}")) + "\n", cancellationToken);
        return new("ManualReview", request.OutputRoot, warnings.Distinct().ToArray(), files, null);
    }

    private static string ConvertJava(string source, ICollection<string> warnings)
    {
        if (source.Contains('@')) warnings.Add("Spring annotations require controller/service attribute mapping.");
        var result = PackageRegex().Replace(source, string.Empty);
        result = ImportRegex().Replace(result, string.Empty);
        result = AnnotationRegex().Replace(result, string.Empty);
        result = ThrowsRegex().Replace(result, string.Empty);
        result = result.Replace("System.out.println", "Console.WriteLine", StringComparison.Ordinal);
        result = result.Replace("System.out.print", "Console.Write", StringComparison.Ordinal);
        result = Regex.Replace(result, @"\bString\b", "string");
        result = Regex.Replace(result, @"\bboolean\b", "bool");
        result = Regex.Replace(result, @"\bInteger\b", "int");
        result = Regex.Replace(result, @"\bLong\b", "long");
        result = Regex.Replace(result, @"\bDouble\b", "double");
        result = Regex.Replace(result, @"\bpublic\s+static\s+void\s+main\s*\(\s*string\[\]\s+args\s*\)", "public static void Main(string[] args)");
        return "// Generated by ForgeShift. Review before use.\nusing System;\nusing System.Collections.Generic;\n\n" + result.Trim() + Environment.NewLine;
    }

    [GeneratedRegex(@"^\s*package\s+[^;]+;\s*$", RegexOptions.Multiline)] private static partial Regex PackageRegex();
    [GeneratedRegex(@"^\s*import\s+[^;]+;\s*$", RegexOptions.Multiline)] private static partial Regex ImportRegex();
    [GeneratedRegex(@"^\s*@[A-Za-z_$][\w$]*(?:\([^\r\n]*\))?\s*$", RegexOptions.Multiline)] private static partial Regex AnnotationRegex();
    [GeneratedRegex(@"\s+throws\s+[A-Za-z_$][\w$]*(?:\s*,\s*[A-Za-z_$][\w$]*)*")] private static partial Regex ThrowsRegex();

    private static string ConvertProperties(string source)
    {
        var values = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var line in source.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            if (line.StartsWith('#') || !line.Contains('=')) continue;
            var parts = line.Split('=', 2);
            values[parts[0].Trim()] = parts[1].Trim();
        }
        return JsonSerializer.Serialize(new { SpringBoot = values }, new JsonSerializerOptions { WriteIndented = true }) + Environment.NewLine;
    }
}
using System.Text.RegularExpressions;
using MigrationPlatform.MigrationEngine.Interfaces;
using MigrationPlatform.MigrationEngine.Models;

namespace MigrationPlatform.MigrationEngine.Providers;

public sealed partial class ReactToReactNativeProvider : IMigrationProvider
{
    public bool CanHandle(string sourceTechnology, string targetTechnology) => sourceTechnology.Equals("React Web", StringComparison.OrdinalIgnoreCase) && targetTechnology.Equals("React Native", StringComparison.OrdinalIgnoreCase);

    public async Task<MigrationResult> ExecuteAsync(MigrationRequest request, CancellationToken cancellationToken)
    {
        if (!Directory.Exists(request.SourceRoot)) return new("Failed", null, [], [], "The source workspace does not exist.");
        Directory.CreateDirectory(request.OutputRoot);
        var files = new List<string>();
        var warnings = new HashSet<string>();
        foreach (var sourceFile in Directory.EnumerateFiles(request.SourceRoot, "*", SearchOption.AllDirectories))
        {
            cancellationToken.ThrowIfCancellationRequested();
            var relative = Path.GetRelativePath(request.SourceRoot, sourceFile);
            var extension = Path.GetExtension(relative);
            var isComponent = extension is ".jsx" or ".tsx" or ".js" or ".ts";
            var destinationRelative = isComponent ? relative : relative;
            var destination = Path.Combine(request.OutputRoot, destinationRelative);
            Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
            if (isComponent)
            {
                var source = await File.ReadAllTextAsync(sourceFile, cancellationToken);
                await File.WriteAllTextAsync(destination, Transform(source, warnings), cancellationToken);
            }
            else
            {
                await using var input = File.OpenRead(sourceFile);
                await using var output = File.Create(destination);
                await input.CopyToAsync(output, cancellationToken);
            }
            files.Add(destinationRelative);
        }
        await File.WriteAllTextAsync(Path.Combine(request.OutputRoot, "FORGESHIFT-MANUAL-REVIEW.md"), "# Manual review required\n\nCommon JSX elements were mapped to React Native primitives. Browser APIs, CSS, routing, storage, and platform-specific behavior require review.\n\n## Warnings\n\n" + string.Join("\n", warnings.Select(warning => $"- {warning}")) + "\n", cancellationToken);
        return new("ManualReview", request.OutputRoot, warnings.ToArray(), files, null);
    }

    private static string Transform(string source, ISet<string> warnings)
    {
        if (source.Contains("window.", StringComparison.Ordinal) || source.Contains("document.", StringComparison.Ordinal)) warnings.Add("Browser APIs require React Native replacements.");
        if (source.Contains("className", StringComparison.Ordinal) || source.Contains(".css", StringComparison.OrdinalIgnoreCase)) warnings.Add("CSS and className values require StyleSheet conversion.");
        if (source.Contains("react-router", StringComparison.OrdinalIgnoreCase)) warnings.Add("React Router requires React Navigation mapping.");
        var result = source.Replace("className", "style", StringComparison.Ordinal);
        result = TagRegex("div").Replace(result, "View");
        result = TagRegex("section").Replace(result, "View");
        result = TagRegex("span").Replace(result, "Text");
        result = TagRegex("p").Replace(result, "Text");
        result = TagRegex("button").Replace(result, "Pressable");
        result = TagRegex("img").Replace(result, "Image");
        result = result.Replace("from \"react\"", "from \"react\"", StringComparison.Ordinal);
        return "// Generated by ForgeShift. Review before use.\n" + result.Trim() + Environment.NewLine;
    }

    private static Regex TagRegex(string tag) => new($"</?{tag}(?=[\\s>])", RegexOptions.Compiled | RegexOptions.IgnoreCase);
}